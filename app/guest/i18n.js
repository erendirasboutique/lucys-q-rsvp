export function fmtTime(t, lang) {
  const m = /^(\d{1,2}):(\d{2})$/.exec(String(t || ""));
  if (!m) return t || "";
  const h = Number(m[1]);
  const suffix = lang === "es" ? (h < 12 ? "a. m." : "p. m.") : h < 12 ? "AM" : "PM";
  return `${((h + 11) % 12) + 1}:${m[2]} ${suffix}`;
}

export function fmtDate(d, lang, opts = { weekday: "short", month: "short", day: "numeric" }) {
  if (!/^\d{4}-\d{2}-\d{2}$/.test(String(d || ""))) return d || "";
  return new Intl.DateTimeFormat(lang === "es" ? "es-MX" : "en-US", { ...opts, timeZone: "UTC" }).format(new Date(`${d}T12:00:00Z`));
}
